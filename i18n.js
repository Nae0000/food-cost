const CURRENCIES = {
    THB: { symbol: '฿', name: 'บาท (THB)', rate: 1, decimals: 2 },
    USD: { symbol: '$', name: 'Dollar (USD)', rate: 1, decimals: 2 },
    JPY: { symbol: '¥', name: '日本円 (JPY)', rate: 1, decimals: 2 },
};

const SETTINGS_KEY = 'fc_settings';

function loadSettings() {
    try { return JSON.parse(localStorage.getItem(SETTINGS_KEY)) || {}; } catch { return {}; }
}
function saveSettings(s) {
    // 1. Save local
    localStorage.setItem(SETTINGS_KEY, JSON.stringify(s));

    // 2. Save to Firestore (so it syncs across devices)
    if (typeof dbFirestore !== 'undefined' && typeof auth !== 'undefined' && auth.currentUser) {
        dbFirestore.collection('users').doc(auth.currentUser.uid)
            .set({ settings: s }, { merge: true })
            .catch(err => console.error("Error saving settings to Firestore", err));
    }
}

// Current settings (live)
let _settings = { lang: 'th', currency: 'JPY', customRate: null, calcMethod: 'margin', taxTakeOut: 8, taxDineIn: 10, ...loadSettings() };

// t(key) — translate a key
function t(key) {
    const tr = TRANSLATIONS[_settings.lang] || TRANSLATIONS.th;
    return tr[key] || TRANSLATIONS.th[key] || key;
}

// formatPrice(val) — format number as currency string
function formatPrice(val) {
    const cur = CURRENCIES[_settings.currency] || CURRENCIES.THB;
    const converted = (val || 0) * cur.rate;
    return cur.symbol + converted.toFixed(cur.decimals).replace(/\B(?=(\d{3})+(?!\d))/g, ',');
}

// Apply language to sidebar (called on settings change)
function applyI18n() {
    document.querySelectorAll('[data-page]').forEach(el => {
        const page = el.dataset.page;
        const keyMap = {
            dashboard: 'nav_dashboard', categories: 'nav_categories', ingredients: 'nav_ingredients',
            menus: 'nav_menus', recipes: 'nav_recipes', webhook: 'nav_webhook', settings: 'nav_settings',
            receipts: 'nav_receipts', 'price-history': 'nav_price_history'
        };
        const label = el.querySelector('.nav-label') || el.querySelector('.bottom-nav-label') || el.querySelector('span:not(.more-item-icon)');
        if (label && keyMap[page]) label.textContent = t(keyMap[page]);
    });

    const logoutBtn = document.getElementById('logoutBtn');
    if (logoutBtn) logoutBtn.lastChild.textContent = ' ' + t('btn_logout');

    const mLogoutBtn = document.getElementById('mobileLogoutBtn');
    if (mLogoutBtn && mLogoutBtn.lastElementChild) mLogoutBtn.lastElementChild.textContent = t('btn_logout');

    const moreBtn = document.getElementById('moreMenuBtn');
    if (moreBtn && moreBtn.querySelector('.bottom-nav-label')) moreBtn.querySelector('.bottom-nav-label').textContent = t('nav_more');

    const moreHeader = document.querySelector('.more-overlay-header span');
    if (moreHeader && !moreHeader.children.length) moreHeader.textContent = t('nav_more_menu');
}
